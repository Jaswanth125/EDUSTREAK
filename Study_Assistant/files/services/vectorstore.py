import os
import chromadb
from chromadb.utils import embedding_functions

class VectorStoreClient:
    """
    A client for interacting with a ChromaDB vector store.
    
    This class manages the creation, connection, and data storage operations
    for a persistent ChromaDB collection.
    """
    def __init__(self, store_path='./vectorstore', collection_name='rag_collection'):
        """
        Initializes the VectorStoreClient.

        Args:
            store_path (str): The directory path for the persistent ChromaDB store.
            collection_name (str): The name of the collection to be used.
        """
        if not os.path.exists(store_path):
            os.makedirs(store_path)
            print(f"Created vector store directory at: {store_path}")

        self.client = chromadb.PersistentClient(path=store_path)
        
        # Using a default sentence transformer embedding function from chromadb.utils
        # This is used by ChromaDB internally if embeddings are not provided.
        # However, we will provide our own embeddings generated by `EmbeddingClient`.
        sentence_transformer_ef = embedding_functions.SentenceTransformerEmbeddingFunction(model_name="all-MiniLM-L6-v2")
        
        self.collection = self.client.get_or_create_collection(
            name=collection_name,
            embedding_function=sentence_transformer_ef
        )
        print(f"Connected to ChromaDB collection: {collection_name}")

    def add_documents(self, documents, embeddings, metadatas, ids):
        """
        Adds documents and their corresponding embeddings to the collection.

        Args:
            documents (list of str): The text content of the documents.
            embeddings (list of list of float): The embeddings for the documents.
            metadatas (list of dict): Metadata associated with each document.
            ids (list of str): Unique IDs for each document.
        """
        self.collection.add(
            embeddings=embeddings,
            documents=documents,
            metadatas=metadatas,
            ids=ids
        )
        print(f"Added {len(documents)} documents to the vector store.")

    def query(self, query_embedding, n_results=5, where=None):
        """
        Queries the collection to find the most similar documents.

        Args:
            query_embedding (list of float): The embedding of the query.
            n_results (int): The number of results to retrieve.
            where (dict): Optional filter conditions (e.g., {"filename": "doc.pdf"}).

        Returns:
            dict: The query results from ChromaDB.
        """
        query_params = {
            "query_embeddings": [query_embedding],
            "n_results": n_results
        }
        if where:
            query_params["where"] = where
        return self.collection.query(**query_params)

    def get_collection_count(self):
        """
        Gets the number of items in the collection.

        Returns:
            int: The total count of items.
        """
        return self.collection.count()
    
    def get_all_documents(self, limit=None, where=None):
        """
        Gets all documents from the collection.
        
        Args:
            limit (int): Optional limit on number of documents to retrieve.
            where (dict): Optional filter conditions (e.g., {"filename": "doc.pdf"}).
        
        Returns:
            dict: All documents with their metadata.
        """
        get_params = {}
        if limit:
            get_params["limit"] = limit
        if where:
            get_params["where"] = where
        
        all_data = self.collection.get(**get_params) if get_params else self.collection.get()
        
        count = len(all_data.get("documents", []))
        if count == 0:
            return {"documents": [[]], "ids": [[]], "metadatas": [[]]}
        
        # Format to match query() return format
        return {
            "documents": [all_data.get("documents", [])],
            "ids": [all_data.get("ids", [])],
            "metadatas": [all_data.get("metadatas", [])]
        }
    
    def get_unique_filenames(self):
        """
        Gets a list of unique filenames from the collection.
        
        Returns:
            list: List of unique filenames.
        """
        try:
            all_data = self.collection.get()
            filenames = set()
            metadatas = all_data.get("metadatas", [])
            
            # Handle both list of lists and list of dicts
            if metadatas:
                if isinstance(metadatas[0], list):
                    # Flatten list of lists
                    for metadata_list in metadatas:
                        for metadata in metadata_list:
                            if metadata and isinstance(metadata, dict) and "filename" in metadata:
                                filenames.add(metadata["filename"])
                else:
                    # List of dicts
                    for metadata in metadatas:
                        if metadata and isinstance(metadata, dict) and "filename" in metadata:
                            filenames.add(metadata["filename"])
            
            return sorted(list(filenames))
        except Exception as e:
            print(f"Error getting unique filenames: {e}")
            return []